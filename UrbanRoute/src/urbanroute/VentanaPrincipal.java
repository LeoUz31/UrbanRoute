    /**
     * Cierra la aplicación; si hay cambios sin guardar muestra antes la alerta 3.1
     * (Cancelar o un guardado fallido mantienen la ventana abierta).
     * Se usa System.exit porque el visor de GraphStream mantiene hilos propios activos.
     */
    private void salir() {
        if (confirmarDescartarCambios()) {
            dispose();
            System.exit(0);
        }
    }

    // ---------------------------------------------------------------- Flujo de archivos

    /**
     * Si hay cambios pendientes, muestra la alerta 3.1 y actúa según la respuesta.
     *
     * @return true si se puede continuar (se guardó o se descartaron los cambios)
     */
    private boolean confirmarDescartarCambios() {
        if (!controlador.hayCambiosPendientes()) {
            return true;
        }
        int respuesta = MensajesError.confirmarCambiosSinGuardar(this);
        if (respuesta == MensajesError.GUARDAR) {
            return guardar();
        }
        if (respuesta == MensajesError.NO_GUARDAR) {
            return true;
        }
        return false;
    }

    /**
     * Carga la red desde el diccionario y las conexiones. Si hay líneas inválidas muestra
     * el diálogo 3.2; si algún archivo no se puede leer, la red actual se conserva.
     *
     * @param diccionario archivo de estaciones elegido por el usuario
     * @param conexiones archivo de conexiones elegido por el usuario
     */
    private void cargarArchivos(File diccionario, File conexiones) {
        if (diccionario.equals(conexiones)) {
            MensajesError.mostrarAdvertencia(this,
                    "Debe elegir dos archivos distintos: el diccionario y las conexiones.");
            return;
        }
        try {
            ListaEnlazada<String> errores = controlador.cargarRed(diccionario, conexiones);
            refrescarVista();
            estado.mostrarMensaje("Red cargada: " + controlador.getGrafo().numVertices()
                    + " estaciones, " + contarConexiones() + " conexiones");
            if (!errores.estaVacia()) {
                MensajesError.mostrarErroresParseo(this, errores,
                        controlador.getGrafo().numVertices(), contarConexiones());
            }
        } catch (IOException ex) {
            MensajesError.mostrarError(this, "Error de lectura del archivo",
                    "No se pudieron leer los archivos. La red actual no cambió.\n" + ex.getMessage());
        }
    }

    /**
     * Guarda en los archivos actuales; si no hay archivos asociados, delega en guardarComo().
     *
     * @return true si los datos quedaron guardados
     */
    private boolean guardar() {
        try {
            if (controlador.guardarRed()) {
                actualizarEncabezado();
                estado.mostrarMensaje("Red guardada en " + nombresArchivos());
                return true;
            }
        } catch (IOException ex) {
            MensajesError.mostrarError(this, "Error al guardar", ex.getMessage());
            return false;
        }
        return guardarComo();
    }

    /**
     * Pide los dos archivos destino (diccionario y conexiones) y guarda la red en ellos.
     *
     * @return true si los datos quedaron guardados
     */
    private boolean guardarComo() {
        File diccionario = elegirDestino("1/2 · Guardar diccionario de estaciones",
                controlador.getArchivoDiccionario(), "diccionario.csv");
        if (diccionario == null) {
            return false;
        }
        File conexiones = elegirDestino("2/2 · Guardar conexiones del grafo",
                controlador.getArchivoConexiones(), "grafo.csv");
        if (conexiones == null) {
            return false;
        }
        if (diccionario.equals(conexiones)) {
            MensajesError.mostrarAdvertencia(this,
                    "El diccionario y las conexiones deben guardarse en archivos distintos.");
            return false;
        }
        try {
            controlador.guardarRedComo(diccionario, conexiones);
            actualizarEncabezado();
            estado.mostrarMensaje("Red guardada en " + nombresArchivos());
            return true;
        } catch (IOException ex) {
            MensajesError.mostrarError(this, "Error al guardar", ex.getMessage());
            return false;
        }
    }

    /**
     * Muestra un diálogo de guardado. Agrega .csv si el nombre no tiene extensión
     * y confirma antes de sobrescribir un archivo existente.
     *
     * @param titulo título del diálogo
     * @param actual archivo actual para preseleccionar (puede ser null)
     * @param nombrePorDefecto nombre sugerido si no hay archivo actual
     * @return archivo destino o null si se canceló
     */
    private File elegirDestino(String titulo, File actual, String nombrePorDefecto) {
        JFileChooser selector = new JFileChooser();
        selector.setDialogTitle(titulo);
        selector.setFileFilter(new FileNameExtensionFilter("Archivos CSV", "csv", "txt"));
        if (actual != null) {
            selector.setSelectedFile(actual);
        } else {
            selector.setSelectedFile(new File(nombrePorDefecto));
        }
        if (selector.showSaveDialog(this) != JFileChooser.APPROVE_OPTION) {
            return null;
        }
        File archivo = selector.getSelectedFile();
        if (!tieneExtension(archivo.getName())) {
            archivo = new File(archivo.getParentFile(), archivo.getName() + ".csv");
        }
        if (archivo.exists() && !MensajesError.confirmarSobrescribir(this, archivo.getName())) {
            return null;
        }
        return archivo;
    }

    /** @return "diccionario.csv + grafo.csv", o null si la red no tiene archivos asociados */
    private String nombresArchivos() {
        File d = controlador.getArchivoDiccionario();
        File c = controlador.getArchivoConexiones();
        if (d == null || c == null) {
            return null;
        }
        return d.getName() + " + " + c.getName();
    }

