    /**
     * Punto único de actualización de la vista tras cualquier cambio en la red real:
     * título, barra de estado, mapa, combos de ambos paneles y resultados.
     * (El controlador ya descartó la simulación de cierres al modificar la red.)
     */
    public void refrescarVista() {
        actualizarEncabezado();
        renderizador.dibujar(controlador.getGrafo());
        ListaEnlazada<Estacion> lista = UtilVista.ordenarPorNombre(controlador.obtenerEstaciones());
        edicion.cargarEstaciones(lista);
        edicion.actualizarCerradas();
        analisis.cargarEstaciones(lista);
        analisis.limpiarResultados(true);
        repintarMapa();
    }

    /**
     * Se llama al cerrar o restablecer estaciones en la simulación: borra los resultados
     * de ruta/subredes (ya no son válidos) y repinta el mapa con las estaciones cerradas.
     */
    public void simulacionCambiada() {
        analisis.limpiarResultados(false);
        repintarMapa();
    }

    /** Estilo base del mapa: sin resaltados, tamaño por grado y estaciones cerradas en gris. */
    public void repintarMapa() {
        renderizador.limpiarResaltado();
        renderizador.escalarPorGrado(controlador.getGrafo());
        renderizador.marcarCerradas(controlador.getCerradas());
    }

    /**
     * Muestra un mensaje en la barra de estado.
     *
     * @param mensaje texto a mostrar
     */
    public void mostrarMensaje(String mensaje) {
        estado.mostrarMensaje(mensaje);
    }

    /** Actualiza título (archivos y marca de cambios "*") y contadores de la barra de estado. */
    private void actualizarEncabezado() {
        String titulo = "UrbanRoute";
        String nombreArchivo = nombresArchivos();
        if (nombreArchivo != null) {
            titulo = titulo + " — " + nombreArchivo;
        }
        if (controlador.hayCambiosPendientes()) {
            titulo = titulo + " *";
        }
        setTitle(titulo);
        estado.actualizar(nombreArchivo, controlador.getGrafo().numVertices(), contarConexiones());
    }

    /** @return número de conexiones (no dirigidas) de la red */
    private int contarConexiones() {
        return controlador.getGrafo().obtenerAristasUnicas().getSize();
    }

    /**
     * @param nombre nombre de archivo
     * @return true si contiene un punto después del primer carácter
     */
    private boolean tieneExtension(String nombre) {
        int i = 1;
        while (i < nombre.length()) {
            if (nombre.charAt(i) == '.') {
                return true;
            }
            i++;
        }
        return false;
    }

