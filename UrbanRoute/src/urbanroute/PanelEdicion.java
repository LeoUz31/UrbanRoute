    private void btnAgregarEstacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarEstacionActionPerformed
        String id = txtId.getText().trim();
        String nombre = txtNombre.getText().trim();
        String linea = txtLinea.getText().trim();
        String zona = txtZona.getText().trim();
        String capacidadTexto = txtCapacidad.getText().trim();
        if (id.length() == 0 || nombre.length() == 0 || linea.length() == 0
                || zona.length() == 0 || capacidadTexto.length() == 0) {
            MensajesError.mostrarAdvertencia(this, "Complete todos los campos de la estación.");
        } else if (UtilVista.tieneComa(id) || UtilVista.tieneComa(nombre)
                || UtilVista.tieneComa(linea) || UtilVista.tieneComa(zona)) {
            MensajesError.mostrarAdvertencia(this, "Los campos no pueden contener comas (formato CSV).");
        } else {
            int capacidad = parser.aEntero(capacidadTexto);
            if (capacidad == -1) {
                MensajesError.mostrarAdvertencia(this, "La capacidad debe ser un número entero positivo.");
            } else if (!controlador.agregarEstacion(new Estacion(id, nombre, linea, zona, capacidad))) {
                MensajesError.mostrarAdvertencia(this, "Ya existe una estación con el ID «" + id + "».");
            } else {
                limpiarCamposEstacion();
                ventana.refrescarVista();
                ventana.mostrarMensaje("Estación «" + nombre + "» agregada");
            }
        }
    }//GEN-LAST:event_btnAgregarEstacionActionPerformed

    private void btnEliminarEstacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarEstacionActionPerformed
        Estacion e = UtilVista.seleccionada(cmbEstacionEliminar, estaciones);
        if (e == null) {
            MensajesError.mostrarAdvertencia(this, "Seleccione una estación.");
        } else if (MensajesError.confirmar(this, "Eliminar estación",
                "¿Eliminar «" + e.getNombre() + "» y todas sus conexiones de la red?")) {
            if (controlador.eliminarEstacion(e.getIdEstacion())) {
                ventana.refrescarVista();
                ventana.mostrarMensaje("Estación «" + e.getNombre() + "» eliminada");
            }
        }
    }//GEN-LAST:event_btnEliminarEstacionActionPerformed

    private void btnAgregarConexionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarConexionActionPerformed
        Estacion origen = UtilVista.seleccionada(cmbOrigen, estaciones);
        Estacion destino = UtilVista.seleccionada(cmbDestino, estaciones);
        if (validarExtremos(origen, destino)) {
            double tiempo = parser.aDecimal(txtTiempo.getText().trim());
            if (tiempo <= 0) {
                MensajesError.mostrarAdvertencia(this, "El tiempo debe ser un número mayor que 0.");
            } else if (controlador.agregarConexion(origen.getIdEstacion(), destino.getIdEstacion(), tiempo)) {
                txtTiempo.setText("");
                ventana.refrescarVista();
                ventana.mostrarMensaje("Conexión " + origen.getNombre() + " – " + destino.getNombre()
                        + " (" + RenderizadorGraphStream.formatearTiempo(tiempo) + " min) guardada");
            } else {
                MensajesError.mostrarAdvertencia(this, "No se pudo crear la conexión.");
            }
        }
    }//GEN-LAST:event_btnAgregarConexionActionPerformed

    private void btnEliminarConexionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarConexionActionPerformed
        Estacion origen = UtilVista.seleccionada(cmbOrigen, estaciones);
        Estacion destino = UtilVista.seleccionada(cmbDestino, estaciones);
        if (validarExtremos(origen, destino)) {
            if (controlador.eliminarConexion(origen.getIdEstacion(), destino.getIdEstacion())) {
                ventana.refrescarVista();
                ventana.mostrarMensaje("Conexión " + origen.getNombre() + " – " + destino.getNombre() + " eliminada");
            } else {
                MensajesError.mostrarAdvertencia(this, "No existe una conexión entre «"
                        + origen.getNombre() + "» y «" + destino.getNombre() + "».");
            }
        }
    }//GEN-LAST:event_btnEliminarConexionActionPerformed

    private void btnCerrarEstacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCerrarEstacionActionPerformed
        Estacion e = UtilVista.seleccionada(cmbCierre, estaciones);
        if (e == null) {
            MensajesError.mostrarAdvertencia(this, "Seleccione una estación.");
        } else if (!controlador.cerrarEstacionSimulada(e.getIdEstacion())) {
            MensajesError.mostrarAdvertencia(this, "La estación «" + e.getNombre() + "» ya está cerrada.");
        } else {
            actualizarCerradas();
            ventana.simulacionCambiada();
            // El BFS se ejecuta aquí una vez; "Detectar subredes" reutiliza este resultado.
            int componentes = controlador.detectarSubredes().getSize();
            ventana.mostrarMensaje("Simulación: " + controlador.getCerradas().getSize()
                    + " cerrada(s), " + componentes + " subred(es)");
        }
    }//GEN-LAST:event_btnCerrarEstacionActionPerformed

    private void btnRestablecerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRestablecerActionPerformed
        controlador.restablecerSimulacion();
        actualizarCerradas();
        ventana.simulacionCambiada();
        ventana.mostrarMensaje("Simulación restablecida");
    }//GEN-LAST:event_btnRestablecerActionPerformed

    /** @return true si origen y destino están seleccionados y son distintos (si no, avisa) */
    private boolean validarExtremos(Estacion origen, Estacion destino) {
        if (origen == null || destino == null) {
            MensajesError.mostrarAdvertencia(this, "Seleccione origen y destino.");
            return false;
        }
        if (origen == destino) {
            MensajesError.mostrarAdvertencia(this, "El origen y el destino deben ser distintos.");
            return false;
        }
        return true;
    }

    private void limpiarCamposEstacion() {
        txtId.setText("");
        txtNombre.setText("");
        txtLinea.setText("");
        txtZona.setText("");
        txtCapacidad.setText("");
    }

