    /**
     * Vuelve a llenar los combos conservando la selección previa.
     *
     * @param nuevas estaciones ordenadas para mostrar
     */
    public void cargarEstaciones(ListaEnlazada<Estacion> nuevas) {
        Estacion eliminar = UtilVista.seleccionada(cmbEstacionEliminar, estaciones);
        Estacion origen = UtilVista.seleccionada(cmbOrigen, estaciones);
        Estacion destino = UtilVista.seleccionada(cmbDestino, estaciones);
        Estacion cierre = UtilVista.seleccionada(cmbCierre, estaciones);
        estaciones = nuevas;
        UtilVista.llenarCombo(cmbEstacionEliminar, estaciones, eliminar);
        UtilVista.llenarCombo(cmbOrigen, estaciones, origen);
        UtilVista.llenarCombo(cmbDestino, estaciones, destino);
        UtilVista.llenarCombo(cmbCierre, estaciones, cierre);
    }

    /** Actualiza la etiqueta con las estaciones cerradas en la simulación (salto de línea automático). */
    public void actualizarCerradas() {
        ListaEnlazada<Estacion> cerradas = controlador.getCerradas();
        if (cerradas.estaVacia()) {
            lblCerradas.setText("Cerradas: ninguna");
        } else {
            lblCerradas.setText("<html><div style='width:200px'>Cerradas: "
                    + UtilVista.nombres(cerradas) + "</div></html>");
        }
    }

