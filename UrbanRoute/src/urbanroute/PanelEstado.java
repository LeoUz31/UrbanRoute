    /**
     * Actualiza los contadores de la red.
     *
     * @param nombreArchivos nombres de los archivos actuales, p. ej. "diccionario.csv + grafo.csv" (null si no hay)
     * @param estaciones número de estaciones
     * @param conexiones número de conexiones
     */
    public void actualizar(String nombreArchivos, int estaciones, int conexiones) {
        if (nombreArchivos == null) {
            lblArchivo.setText("Archivos: —");
        } else {
            lblArchivo.setText("Archivos: " + nombreArchivos);
        }
        lblEstaciones.setText("Estaciones: " + estaciones);
        lblConexiones.setText("Conexiones: " + conexiones);
    }

