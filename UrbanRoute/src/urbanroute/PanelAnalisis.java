    private void btnCalcularRutaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularRutaActionPerformed
        Estacion origen = UtilVista.seleccionada(cmbOrigen, estaciones);
        Estacion destino = UtilVista.seleccionada(cmbDestino, estaciones);
        if (origen == null || destino == null) {
            MensajesError.mostrarAdvertencia(this, "Seleccione origen y destino.");
        } else if (origen == destino) {
            MensajesError.mostrarAdvertencia(this, "El origen y el destino deben ser distintos.");
        } else {
            Ruta ruta = controlador.calcularRutaOptima(origen.getIdEstacion(), destino.getIdEstacion());
            ventana.repintarMapa();
            if (ruta.esVacia()) {
                txtRuta.setText("Sin ruta entre «" + origen.getNombre() + "» y «" + destino.getNombre() + "».");
                ventana.mostrarMensaje("Ruta no disponible");
                MensajesError.mostrarRutaInexistente(this, origen.getNombre(), destino.getNombre());
            } else {
                renderizador.resaltarRuta(ruta);
                txtRuta.setText(textoRuta(ruta));
                txtRuta.setCaretPosition(0);
                ventana.mostrarMensaje("Ruta óptima: "
                        + RenderizadorGraphStream.formatearTiempo(ruta.getTiempoTotalMinutos()) + " min");
            }
        }
    }//GEN-LAST:event_btnCalcularRutaActionPerformed

