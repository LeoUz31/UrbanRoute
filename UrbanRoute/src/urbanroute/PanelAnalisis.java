    private void btnDetectarSubredesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetectarSubredesActionPerformed
        // El controlador solo ejecuta el BFS si la red activa cambió desde el último cálculo.
        ListaEnlazada<ListaEnlazada<Estacion>> subredes = controlador.detectarSubredes();
        ventana.repintarMapa();
        renderizador.colorearSubredes(subredes, controlador.getGrafo());

        int total = subredes.getSize();
        String etiqueta = "Componentes: " + total;
        if (total > 1) {
            etiqueta = etiqueta + " (red incomunicada)";
        }
        lblComponentes.setText(etiqueta);

        String texto = "";
        if (total == 0) {
            texto = "La red no tiene estaciones activas.";
        }
        int i = 1;
        Nodo<ListaEnlazada<Estacion>> comp = subredes.getCabeza();
        while (comp != null) {
            texto = texto + "Subred " + i + " (" + comp.getDato().getSize() + "): "
                    + UtilVista.nombres(comp.getDato()) + "\n";
            comp = comp.getSiguiente();
            i++;
        }
        txtSubredes.setText(texto);
        txtSubredes.setCaretPosition(0);
        ventana.mostrarMensaje(etiqueta);
    }//GEN-LAST:event_btnDetectarSubredesActionPerformed

    // ---------------------------------------------------------------- Hubs

    private void btnCalcularHubsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularHubsActionPerformed
        int k = controlador.getLector().getParser().aEntero(txtTopK.getText().trim());
        if (k <= 0) {
            MensajesError.mostrarAdvertencia(this, "Top-k debe ser un número entero mayor que 0.");
        } else {
            ListaEnlazada<Estacion> hubs = controlador.obtenerHubs(k);
            if (hubs.estaVacia()) {
                txtHubs.setText("No hay estaciones en la red.");
            } else {
                String texto = UtilVista.rellenar("#", 4) + UtilVista.rellenar("Estación", 16) + "Grado\n";
                int i = 1;
                Nodo<Estacion> n = hubs.getCabeza();
                while (n != null) {
                    Estacion e = n.getDato();
                    texto = texto + UtilVista.rellenar("" + i, 4)
                            + UtilVista.rellenar(e.getNombre(), 16)
                            + controlador.getGrafo().obtenerGrado(e.getIdEstacion()) + "\n";
                    n = n.getSiguiente();
                    i++;
                }
                txtHubs.setText(texto);
                txtHubs.setCaretPosition(0);
                ventana.mostrarMensaje("Hub principal: " + hubs.getCabeza().getDato().getNombre());
            }
        }
    }//GEN-LAST:event_btnCalcularHubsActionPerformed

    /** @return recorrido "A → B → C" y tiempo total de la ruta */
    private String textoRuta(Ruta ruta) {
        String texto = "";
        Nodo<Estacion> n = ruta.getEstaciones().getCabeza();
        while (n != null) {
            if (n != ruta.getEstaciones().getCabeza()) {
                texto = texto + " → ";
            }
            texto = texto + n.getDato().getNombre();
            n = n.getSiguiente();
        }
        return texto + "\nTiempo total: "
                + RenderizadorGraphStream.formatearTiempo(ruta.getTiempoTotalMinutos())
                + " min · " + ruta.getEstaciones().getSize() + " estaciones";
    }

